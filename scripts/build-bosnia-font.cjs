#!/usr/bin/env node
/**
 * Builds the Bosnian plate lettering from assets/fonts/bosnia-glyphs.png
 * (glyph sheet).
 *
 *   node scripts/build-bosnia-font.cjs
 *
 * Writes:
 *   app/lib/bosniaFont.json        glyph outlines (used by /api/plate only)
 *   app/lib/bosniaFontMetrics.ts   widths + cap height (used by the layout)
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");
const { Potrace } = require("potrace");

const ROOT = path.join(__dirname, "..");
const SHEET = path.join(ROOT, "assets/fonts/bosnia-glyphs.png");
const ROWS = ["-0123456789ABCDE", "FGHIJKLMNOPQRSTU", "VWXYZÄÖÜ"]; // the coat-of-arms icons and "no texture" tile on the sheet are ignored
const PAD = 4;

function trace(png) {
  return new Promise((resolve, reject) => {
    const p = new Potrace({ threshold: 128, turdSize: 8, optTolerance: 0.25, alphaMax: 1 });
    p.loadImage(png, (err) => {
      if (err) return reject(err);
      const m = p.getPathTag().match(/ d="([^"]+)"/);
      resolve(m ? m[1].trim() : "");
    });
  });
}

const median = (a) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };

(async () => {
  const { data, info } = await sharp(SHEET).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const on = (x, y) => { const i = (y * w + x) * 4; return data[i + 3] > 128 && data[i] > 200 && data[i + 1] > 200 && data[i + 2] > 200; };

  // 1) bands of rows that contain ink
  const rowHas = Array.from({ length: h }, (_, y) => { for (let x = 0; x < w; x++) if (on(x, y)) return true; return false; });
  const bands = []; let s = -1;
  for (let y = 0; y <= h; y++) { const v = y < h && rowHas[y]; if (v && s < 0) s = y; if (!v && s >= 0) { bands.push([s, y - 1]); s = -1; } }
  if (bands.length < ROWS.length) throw new Error(`expected ${ROWS.length} glyph rows, found ${bands.length}`);

  const glyphs = {};
  const capHeights = [];

  for (let r = 0; r < ROWS.length; r++) {
    const [y0, y1] = bands[r];
    // 2) glyph segments within the band (small gaps inside a glyph are bridged)
    const colHas = Array.from({ length: w }, (_, x) => { for (let y = y0; y <= y1; y++) if (on(x, y)) return true; return false; });
    const segs = []; let a = -1, gap = 0, last = 0;
    for (let x = 0; x <= w; x++) {
      const v = x < w && colHas[x];
      if (v) { if (a < 0) a = x; gap = 0; last = x; }
      else if (a >= 0 && (++gap > 1 || x === w)) { segs.push([a, last]); a = -1; gap = 0; }
    }
    // drop the seal dot / specks (narrow and short)
    const boxes = segs.map(([x0, x1]) => {
      let top = y1, bottom = y0;
      for (let x = x0; x <= x1; x++) for (let y = y0; y <= y1; y++) if (on(x, y)) { if (y < top) top = y; if (y > bottom) bottom = y; }
      return { x0, x1, top, bottom };
    });
    const chars = ROWS[r];
    if (boxes.length < chars.length) throw new Error(`row ${r}: expected ${chars.length} glyphs, found ${boxes.length}`);
    boxes.length = chars.length;

    const caps = boxes.filter((_, i) => !"-ÄÖÜQ".includes(chars[i]));
    const baseline = median(caps.map((b) => b.bottom));
    const capTop = median(caps.map((b) => b.top));
    capHeights.push(baseline - capTop + 1);

    for (let i = 0; i < chars.length; i++) {
      const b = boxes[i];
      const left = Math.max(0, b.x0 - PAD), top = Math.max(0, Math.min(b.top, capTop) - PAD);
      const cw = Math.min(w, b.x1 + PAD + 1) - left, ch = Math.min(h, b.bottom + PAD + 1) - top;
      // black glyph on white for potrace
      const px = Buffer.alloc(cw * ch * 3, 255);
      for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) {
        if (on(left + x, top + y) && left + x >= b.x0 && left + x <= b.x1) { const k = (y * cw + x) * 3; px[k] = px[k + 1] = px[k + 2] = 0; }
      }
      const png = await sharp(px, { raw: { width: cw, height: ch, channels: 3 } }).png().toBuffer();
      const d = await trace(png);
      if (!d) throw new Error(`trace failed for ${chars[i]}`);
      glyphs[chars[i]] = {
        w: b.x1 - b.x0 + 1,      // ink width (sheet px)
        dx: left - b.x0,          // shift so the ink starts at x = 0
        dy: top - baseline,       // shift so the baseline is y = 0 (caps go negative)
        d,
      };
    }
  }

  const capHeight = median(capHeights);
  const out = { source: "assets/fonts/bosnia-glyphs.png ", capHeight, glyphs };
  fs.writeFileSync(path.join(ROOT, "app/lib/bosniaFont.json"), JSON.stringify(out));

  const widths = Object.fromEntries(Object.entries(glyphs).map(([k, g]) => [k, g.w]));
  fs.writeFileSync(path.join(ROOT, "app/lib/bosniaFontMetrics.ts"),
`// Generated by scripts/build-bosnia-font.cjs — do not edit by hand.
// Ink widths of the Austrian plate glyphs, in sheet pixels; capHeight is the capital height.
export const BA_CAP_HEIGHT = ${capHeight};
export const BA_WIDTHS: Record<string, number> = ${JSON.stringify(widths)};
`);
  console.log(`traced ${Object.keys(glyphs).length} glyphs, cap height ${capHeight}px, json ${(fs.statSync(path.join(ROOT, "app/lib/bosniaFont.json")).size / 1024).toFixed(1)} KB`);
})().catch((e) => { console.error(e.message); process.exit(1); });
