#!/usr/bin/env node
/**
 * Metrics of the Czech plate font (assets/fonts/DIN1451-36breit.ttf, "DIN 1451 fette Breitschrift 1936") for the
 * layout engine: capital height and advance widths in em.
 *
 *   node scripts/build-cz-metrics.cjs  →  app/lib/czMetrics.ts
 */
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");
const ROOT = path.join(__dirname, "..");
const f = opentype.loadSync(path.join(ROOT, "assets/fonts/DIN1451-36breit.ttf"));
const em = f.unitsPerEm;
const cap = f.charToGlyph("H").getBoundingBox().y2 / em;
const adv = {};
for (const ch of "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-. ŠŽ·") adv[ch] = Math.round((f.charToGlyph(ch).advanceWidth / em) * 1000) / 1000;
fs.writeFileSync(path.join(ROOT, "app/lib/czMetrics.ts"),
`// Generated by scripts/build-cz-metrics.cjs — do not edit by hand.
export const CZ_CAP_HEIGHT = ${Math.round(cap * 1000) / 1000};
export const CZ_ADVANCE: Record<string, number> = ${JSON.stringify(adv)};
`);
console.log("cap", cap);
