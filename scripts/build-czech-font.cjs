#!/usr/bin/env node
/**
 * Builds the Czech plate lettering from the glyph sheet assets/fonts/czech-glyphs.png
 * (black on white: 1234567890 then ABCDEFHIJKLMNPRSTUVXYZ; the stars under some glyphs are ignored).
 *
 *   node scripts/build-czech-font.cjs
 *
 * Writes app/lib/czechFont.json (outlines, used by /api/plate) and app/lib/czechFontMetrics.ts (widths + cap height).
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");
const { Potrace } = require("potrace");

const ROOT = path.join(__dirname, "..");
const CHARS = "1234567890ABCDEFHIJKLMNPRSTUVXYZ";
const CAP = 560;
const PAD = 12;

function trace(png) {
  return new Promise((resolve, reject) => {
    const p = new Potrace({ threshold: 128, turdSize: 40, optTolerance: 0.5, alphaMax: 1 });
    p.loadImage(png, (err) => { if (err) return reject(err); const m = p.getPathTag().match(/ d="([^"]+)"/); resolve(m ? m[1].trim() : ""); });
  });
}

(async () => {
  const { data, info } = await sharp(path.join(ROOT, "assets/fonts/czech-glyphs.png")).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height;
  const dark = (x, y) => data[(y * W + x) * 3] < 110;
  // main row = the first band of ink
  const rowHas = []; for (let y = 0; y < H; y++) { let d = false; for (let x = 0; x < W && !d; x++) if (dark(x, y)) d = true; rowHas.push(d); }
  const y0 = rowHas.indexOf(true); let y1 = y0; while (y1 + 1 < H && rowHas[y1 + 1]) y1++;
  const cols = []; let a = -1;
  for (let x = 0; x <= W; x++) { let d = false; if (x < W) for (let y = y0; y <= y1 && !d; y++) if (dark(x, y)) d = true; if (d && a < 0) a = x; if (!d && a >= 0) { cols.push([a, x - 1]); a = -1; } }
  if (cols.length !== CHARS.length) throw new Error(`expected ${CHARS.length} glyphs, found ${cols.length}`);

  const capH = y1 - y0 + 1;                 // all capitals and digits share the top and bottom of the row
  const f = CAP / capH;
  const glyphs = {};
  for (let i = 0; i < CHARS.length; i++) {
    const [x0, x1] = cols[i]; const w = x1 - x0 + 1;
    const small = Buffer.alloc(w * capH, 255);
    for (let y = 0; y < capH; y++) for (let x = 0; x < w; x++) if (dark(x0 + x, y0 + y)) small[y * w + x] = 0;
    const big = await sharp(small, { raw: { width: w, height: capH, channels: 1 } })
      .resize(Math.round(w * f), CAP, { kernel: "lanczos3" }).blur(Math.max(1.5, f * 0.7)).threshold(128).toColourspace("b-w")
      .extend({ top: PAD, bottom: PAD, left: PAD, right: PAD, background: { r: 255, g: 255, b: 255 } }).png().toBuffer();
    const d = await trace(big);
    if (!d) throw new Error("trace failed for " + CHARS[i]);
    glyphs[CHARS[i]] = { w: Math.round(w * f), dx: -PAD, dy: -(CAP + PAD), d };
  }
  // O is the zero; the letters G, Q and W are not used on Czech plates
  glyphs.O = glyphs["0"];
  // the dash (not on the sheet): a bar as thick as the stem of the I
  {
    const stem = glyphs.I.w, mid = PAD + Math.round(CAP * 0.5), w = 230;
    glyphs["-"] = { w, dx: -PAD, dy: -(CAP + PAD), d: `M${PAD} ${mid - stem / 2} L${PAD + w} ${mid - stem / 2} L${PAD + w} ${mid + stem / 2} L${PAD} ${mid + stem / 2} Z` };
  }

  fs.writeFileSync(path.join(ROOT, "app/lib/czechFont.json"), JSON.stringify({ source: "assets/fonts/czech-glyphs.png", capHeight: CAP, glyphs }));
  const widths = Object.fromEntries(Object.entries(glyphs).map(([k, g]) => [k, g.w]));
  fs.writeFileSync(path.join(ROOT, "app/lib/czechFontMetrics.ts"),
`// Generated by scripts/build-czech-font.cjs — do not edit by hand.
// Ink widths of the Czech plate glyphs (cap height ${CAP}); capHeight is the capital height.
export const CZF_CAP_HEIGHT = ${CAP};
export const CZF_WIDTHS: Record<string, number> = ${JSON.stringify(widths)};
`);
  console.log("traced", Object.keys(glyphs).length, "glyphs, cap", capH, "px");
})().catch((e) => { console.error(e.message); process.exit(1); });
