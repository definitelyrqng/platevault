#!/usr/bin/env node
/**
 * Metrics of D-DIN (assets/fonts/D-DIN.ttf, SIL OFL, Datto Inc.) for the layout engine:
 * capital height and advance widths, in em. Used for the Croatian plates.
 *
 *   node scripts/build-ddin-metrics.cjs   →  app/lib/ddinMetrics.ts
 */
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");

const ROOT = path.join(__dirname, "..");
const f = opentype.loadSync(path.join(ROOT, "assets/fonts/D-DIN.ttf"));
const em = f.unitsPerEm;
const H = f.charToGlyph("H");
const bb = H.getBoundingBox();
const cap = bb.y2 / em;
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-. ŠŽ";
const adv = {};
for (const ch of chars) adv[ch] = Math.round((f.charToGlyph(ch).advanceWidth / em) * 1000) / 1000;
fs.writeFileSync(path.join(ROOT, "app/lib/ddinMetrics.ts"),
`// Generated by scripts/build-ddin-metrics.cjs — do not edit by hand.
// D-DIN (SIL OFL, Datto Inc.): capital height and advance widths in em.
export const DD_CAP_HEIGHT = ${Math.round(cap * 1000) / 1000};
export const DD_ADVANCE: Record<string, number> = ${JSON.stringify(adv)};
`);
console.log("unitsPerEm", em, "cap", cap);
